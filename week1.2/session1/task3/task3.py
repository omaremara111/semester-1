fruit = ("apple", "banana", "cherry")
print(fruit)

# Find and display position of "banana"
in_banana = fruit.index("banana")
print(in_banana)

# Display how many times "cherry" occurs
cherry_int = fruit.count("cherry")
print(cherry_int)

# Display how many times "strawberry" occurs
strawberry_int = fruit.count("strawberry")
print(strawberry_int)

# Unpack tuple into variables
a, b, c = ("apple", "banana", "cherry")
print(a)
print(b)
print(c)